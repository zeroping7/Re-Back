// Capturas de la interfaz: taller, campeonato, garaje, opciones, carga, carrera, resultados de copa y podio
import puppeteer from 'puppeteer-core';
import fs from 'fs';
const url = process.argv[2] || 'http://localhost:4173/';
const out = process.argv[3] || 'tests/shots/ui';
fs.mkdirSync(out, { recursive: true });
const browser = await puppeteer.launch({ executablePath: '/usr/bin/google-chrome', headless: 'new',
  args: ['--no-sandbox', '--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist', '--autoplay-policy=no-user-gesture-required'] });
const page = await browser.newPage();
await page.setViewport({ width: 900, height: 420, deviceScaleFactor: 1 });
const errors = [];
page.on('pageerror', (e) => errors.push('pageerror: ' + e.message + '\n' + (e.stack || '').split('\n').slice(0, 3).join('\n')));
page.on('console', (m) => { if (m.type() === 'error' || m.type() === 'warning') errors.push(m.type() + ': ' + m.text().slice(0, 300)); });
await page.goto(url, { waitUntil: 'load' });
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const shot = (n) => page.screenshot({ path: `${out}/${n}.png` });
await sleep(2500);
await shot('0-start');
await page.click('#btn-start'); await sleep(2200);
await shot('1-main');
await page.click('[data-go="cups"]'); await sleep(2000);
await shot('2-cups');
await page.evaluate(() => document.querySelectorAll('#cups .card')[1].click()); await sleep(600);
await shot('2b-cups-locked');
await page.click('#m-cups .back'); await sleep(500);
await page.click('[data-go="garage"]'); await sleep(2000);
await shot('3-garage');
await page.evaluate(() => document.querySelectorAll('#g-cars .card')[8].click()); await sleep(1200);
await shot('3b-garage-formula');
await page.click('#m-garage .back'); await sleep(400);
await page.click('[data-go="settings"]'); await sleep(1200);
await shot('4-settings');
await page.click('#m-settings .back'); await sleep(400);
await page.click('[data-go="practice"]'); await sleep(1200);
await shot('5-practice');
await page.click('#m-setup .back'); await sleep(400);
await page.evaluate(() => window.__game.startCup('bronce')); await sleep(400);
await shot('6-loading');
await page.waitForFunction(() => window.__game.race, { timeout: 60000 });
await sleep(4500);
await shot('7-race');
await page.evaluate(() => { const r = window.__game.race; r.phase = 'done'; r.onFinish(r.results()); }); await sleep(900);
await shot('8-results-cup');
await page.evaluate(() => { window.__game.cup.idx = 2; const r = window.__game.race; r.onFinish(r.results()); }); await sleep(900);
await shot('9-results-last');
await page.evaluate(() => [...document.querySelectorAll('#res-btns button')][0].click()); await sleep(2500);
await shot('10-podium');
console.log('ERRORS:\n' + errors.slice(0, 20).join('\n'));
await browser.close();

const fakeCtx = new Proxy({}, { get: (t, k) => (k in t ? t[k] : () => ({ addColorStop() {} })), set: (t, k, v) => ((t[k] = v), true) });
globalThis.document = { createElement: () => ({ width: 0, height: 0, getContext: () => fakeCtx }) };
globalThis.localStorage = { getItem: () => null, setItem() {} };
const THREE = await import('three');
const RAPIER = (await import('@dimforge/rapier3d-compat')).default; await RAPIER.init();
const { Car } = await import('../src/car.js');
const { tuning } = await import('../src/tuning.js');
Object.assign(tuning, JSON.parse(process.argv[2] || '{}'));
const world = new RAPIER.World({ x: 0, y: -tuning.gravity, z: 0 }); world.timestep = 1 / 60;
const g = world.createRigidBody(RAPIER.RigidBodyDesc.fixed());
world.createCollider(RAPIER.ColliderDesc.cuboid(500, 1, 500).setTranslation(0, -1, 0), g);
const car = new Car(new THREE.Scene(), world, RAPIER, tuning);
car.reset(new THREE.Vector3(0, 0, -400), 0);
const run = (inp, secs, label) => { for (let i = 0; i < secs * 60; i++) { car.step(1 / 60, inp); world.step(); car.afterStep(1 / 60);
  if (i % 12 === 0) console.log(label, `v=${car.fwdSpeed.toFixed(1)} lat=${car.localVel.x.toFixed(1)} yawRate=${car.body.angvel().y.toFixed(2)} up=${car.up.y.toFixed(2)} drift=${car.drifting}`); } };
run({ steer: 0, throttle: 1, brake: 0 }, 2.5, 'accel');
run({ steer: process.env.STEERONLY ? 1 : 1, throttle: process.env.STEERONLY ? 1 : 0, brake: process.env.STEERONLY ? 0 : 1 }, 1.2, process.env.STEERONLY ? 'turn' : 'drift');
run({ steer: -0.3, throttle: 1, brake: 0 }, 1.0, 'exit');
